import pytest

from times import time_range, compute_overlap_time


def test_given_input():
    """测试题目提供的示例。"""
    large = time_range(
        "2010-01-12 10:00:00",
        "2010-01-12 12:00:00"
    )

    short = time_range(
        "2010-01-12 10:30:00",
        "2010-01-12 10:45:00",
        2,
        60
    )

    result = compute_overlap_time(large, short)

    expected = [
        ("2010-01-12 10:30:00", "2010-01-12 10:37:00"),
        ("2010-01-12 10:38:00", "2010-01-12 10:45:00")
    ]

    assert result == expected


@pytest.mark.parametrize(
    "range1, range2, expected",
    [
        # 第一段早于第二段，完全不重叠
        (
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")],
            [("2010-01-12 12:00:00", "2010-01-12 13:00:00")],
            []
        ),

        # 第一段晚于第二段，完全不重叠
        (
            [("2010-01-12 12:00:00", "2010-01-12 13:00:00")],
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")],
            []
        ),

        # 部分重叠
        (
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")],
            [("2010-01-12 10:30:00", "2010-01-12 12:00:00")],
            [("2010-01-12 10:30:00", "2010-01-12 11:00:00")]
        ),

        # 第一段包含第二段
        (
            [("2010-01-12 10:00:00", "2010-01-12 12:00:00")],
            [("2010-01-12 10:30:00", "2010-01-12 11:00:00")],
            [("2010-01-12 10:30:00", "2010-01-12 11:00:00")]
        ),

        # 第二段包含第一段
        (
            [("2010-01-12 10:30:00", "2010-01-12 11:00:00")],
            [("2010-01-12 10:00:00", "2010-01-12 12:00:00")],
            [("2010-01-12 10:30:00", "2010-01-12 11:00:00")]
        ),

        # 两段完全相同
        (
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")],
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")],
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")]
        ),

        # 仅端点接触：约定不算正时长的重叠
        (
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")],
            [("2010-01-12 11:00:00", "2010-01-12 12:00:00")],
            []
        ),

        # 第一个输入为空
        (
            [],
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")],
            []
        ),

        # 第二个输入为空
        (
            [("2010-01-12 10:00:00", "2010-01-12 11:00:00")],
            [],
            []
        ),

        # 两个输入都为空
        (
            [],
            [],
            []
        ),

        # 跨越午夜
        (
            [("2010-01-12 23:00:00", "2010-01-13 01:00:00")],
            [("2010-01-13 00:30:00", "2010-01-13 02:00:00")],
            [("2010-01-13 00:30:00", "2010-01-13 01:00:00")]
        ),

        # 多段输入：既有重叠，也有不重叠
        (
            [
                ("2010-01-12 10:00:00", "2010-01-12 11:00:00"),
                ("2010-01-12 12:00:00", "2010-01-12 13:00:00")
            ],
            [
                ("2010-01-12 10:30:00", "2010-01-12 12:30:00"),
                ("2010-01-12 14:00:00", "2010-01-12 15:00:00")
            ],
            [
                ("2010-01-12 10:30:00", "2010-01-12 11:00:00"),
                ("2010-01-12 12:00:00", "2010-01-12 12:30:00")
            ]
        )
    ],
    ids=[
        "no_overlap_before",
        "no_overlap_after",
        "partial_overlap",
        "first_contains_second",
        "second_contains_first",
        "identical",
        "touching_endpoints",
        "empty_first",
        "empty_second",
        "both_empty",
        "across_midnight",
        "multiple_intervals"
    ]
)
def test_compute_overlap_time(range1, range2, expected):
    """每组参数都会作为一个独立测试运行。"""
    result = compute_overlap_time(range1, range2)
    assert result == expected